def texts(count: int) -> list[str]:
    chosen = random.Random(20261123)
    found = list(dict.fromkeys(BY_HAND))
    seen = set(found)
    while len(found) < len(BY_HAND) + count:
        text = chosen.choice(SEEDS)
        for _ in range(chosen.choice((1, 1, 1, 2, 3))):
            at = chosen.randrange(len(text) + 1)
            piece = chosen.choice(PIECES)
            # put a piece in, or take the character there away, or put the piece in its place
            text = text[:at] + piece + text[at + chosen.choice((0, 1, 1)):]
        if text not in seen:
            seen.add(text)
            found.append(text)
    return found


def answer(text: str) -> dict[str, str | None]:
    """The instant, or why there is none: no zone, a time that cannot be moved to UTC, or
    anything else."""
    try:
        return {"utc": _timestamp(text).strftime("%Y-%m-%dT%H:%M:%S.%f").rjust(26, "0")}
    except OverflowError:
        return {"utc": None, "refused": "out-of-range"}
    except ValueError as err:
        naive = str(err) == "timestamp must include a timezone"
        return {"utc": None, "refused": "naive" if naive else "invalid"}


def main(out: str, count: int = 3000) -> None:
    with open(out, "w", encoding="ascii", newline="\n") as stream:
        stream.writelines(json.dumps({"text": text, **answer(text)}) + "\n"
                          for text in texts(count))


if __name__ == "__main__":
    main(sys.argv[1], *(int(arg) for arg in sys.argv[2:3]))
