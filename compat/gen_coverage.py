"""Writes compat/COVERAGE.md: one line per Python test function, targets kept.

    uv run python compat/gen_coverage.py
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from fnmatch import fnmatchcase
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
LEDGER = REPO / "compat" / "COVERAGE.md"
HEADER = """# Coverage ledger

One line per Python test function: where its behaviour is tested for the Rust
implementation. Generated by `compat/gen_coverage.py`, which keeps the targets
already filled in; checked by `compat/test_coverage_ledger.py`.

A target is `compat:<file>::<case>`, `rust:<crate>::<module path>::<test>`, several
of those joined by ` + `, or `n/a: <reason>`, or `n/a until phase <n>: <reason>` for what a
later phase tests (when that phase is finished the line must name its test). A target that is named must exist: a
Rust target's path names a file and then the inline modules that contain the test,
in order. The file is given by its modules from the crate root
(`models::helpers::tests::name` is in `src/models/helpers.rs` or
`src/models/helpers/mod.rs`, inside `mod tests`; no module means `src/lib.rs`) or by
its place in the crate (`tests/cli_version.rs::name`, `src/main.rs::tests::name`).
The name must be a test function in exactly those inline modules of that file.
The crate is the name of one directory of `crates/`, and the file one that really
lies in it (in `compat/` for a compat target): no absolute path, no link out.
When a phase is finished its number is added to `finished phases:` together with
a line `phase <n>: <glob>, <glob>, ...` naming the Python test files it covers;
from then on every function of those files needs a target, and a glob that matches
no test file is an error.

finished phases:
"""
_TEST = re.compile(r"^\s*(?:async\s+)?def\s+(test_\w+)", re.MULTILINE)
_ENTRY = re.compile(r"^(\S+\.py::\w+) -> ?(.*)$")
_FINISHED = re.compile(r"^finished phases:(.*)$")
_PHASE = re.compile(r"^phase (\d+):(.*)$")
_PUT_OFF = re.compile(r"^n/a until phase (\d+):")


@dataclass
class Ledger:
    header: str = ""
    finished: list[int] = field(default_factory=list)
    phases: dict[int, list[str]] = field(default_factory=dict)
    targets: dict[str, str] = field(default_factory=dict)


def listing(repo: Path) -> list[str]:
    """`<path>::<function>` for every test function of the Python tree, sorted."""
    files = [*repo.glob("packages/*/tests/**/*.py"), *repo.glob("tools/*.py")]
    return sorted({f"{path.relative_to(repo).as_posix()}::{name}"
                   for path in files for name in _TEST.findall(path.read_text(encoding="utf-8"))})


def parse(text: str) -> Ledger:
    ledger = Ledger()
    header = []
    for line in text.splitlines():
        if entry := _ENTRY.match(line):
            ledger.targets[entry[1]] = entry[2].strip()
            continue
        if not ledger.targets:
            header.append(line)
        if finished := _FINISHED.match(line):
            ledger.finished = [int(n) for n in re.findall(r"\d+", finished[1])]
        elif phase := _PHASE.match(line):
            ledger.phases[int(phase[1])] = [g.strip() for g in phase[2].split(",") if g.strip()]
    ledger.header = "\n".join(header).rstrip("\n") + "\n"
    return ledger


def _file_in(path: Path, directory: Path) -> bool:
    """Whether `path` is a file that really lies in `directory` -- a directory of the
    repository, written from the repository's real place: an absolute name, a `..` or a
    link that leads anywhere else makes it another file."""
    return path.is_file() and path.resolve().is_relative_to(directory)


def _exists(target: str, repo: Path) -> bool:
    repo = repo.resolve()
    kind, _, rest = target.partition(":")
    parts = rest.split("::")
    if kind == "compat" and len(parts) == 2:
        path = repo / "compat" / parts[0]
        return _file_in(path, repo / "compat") and re.search(
            rf"^def {re.escape(parts[1])}\(", path.read_text(), re.MULTILINE) is not None
    # the crate is one of this repository's, by its name alone
    if kind == "rust" and len(parts) >= 2 and ".." not in rest and re.fullmatch(r"[\w-]+", parts[0]):
        return _rust_test(repo / "crates" / parts[0], parts[1:-1], parts[-1])
    return False


def _rust_test(crate: Path, path: list[str], name: str) -> bool:
    """Whether `name` is a test function at `path` of the crate. The path names a file
    and then the inline modules, in order, that contain the test: the file either by its
    place in the crate (`src/main.rs`, `tests/x.rs`) or by its modules from the crate
    root (`a::b` is src/a/b.rs or src/a/b/mod.rs, nothing is src/lib.rs), taking as many
    leading modules as make a file. The file must really lie in the crate (`crate` is
    written from the repository's real place)."""
    if path and path[0].endswith(".rs"):
        file, inline = crate / path[0], path[1:]
    else:
        if not all(re.fullmatch(r"\w+", module) for module in path):
            return False
        for cut in range(len(path), -1, -1):
            inside = crate.joinpath("src", *path[:cut])
            file = next((f for f in ([inside.with_suffix(".rs"), inside / "mod.rs"] if cut
                                     else [inside / "lib.rs"]) if f.is_file()), None)
            if file is not None:
                break
        else:
            return False
        inline = path[cut:]
    return _file_in(file, crate) and (*inline, name) in _rust_tests(file.read_text(encoding="utf-8"))


# What may hold a brace or a quote that is not code: a line comment, the start of a block
# comment (they nest, so its end is found by counting), a raw string with its own number
# of `#`, a string, a character. A lifetime (`'a`) has no closing quote and is none of these.
_RUST_QUIET = re.compile(r"""//[^\n]*|(?P<block>/\*)"""
                         r"""|(?<!\w)(?:b|c)?r(?P<hashes>\#*)".*?"(?P=hashes)"""
                         r"""|(?<!\w)(?:b|c)?"(?:\\.|[^"\\])*\""""
                         r"""|(?<!\w)b?'(?:\\(?:u\{[^}]*\}|.)|[^'\\])'""", re.DOTALL)
_RUST_BLOCK_EDGE = re.compile(r"/\*|\*/")
# an inline module opening, a function with a test attribute (whatever other attributes
# stand between), or a brace
_RUST_TOKEN = re.compile(
    r"\bmod\s+(?P<module>\w+)\s*\{"
    r"|#\[(?:\w+::)*test\b[^\]]*\]\s*(?:#\[[^\]]*\]\s*)*(?:pub(?:\([^)]*\))?\s+)?"
    r"(?:(?:async|const|unsafe)\s+)*fn\s+(?P<test>\w+)\s*\("
    r"|(?P<open>\{)|(?P<close>\})")


def _rust_code(source: str) -> str:
    """A Rust source with every comment and every string and character literal replaced
    by a space, so that what is left of braces and names is code."""
    kept, at = [], 0
    while found := _RUST_QUIET.search(source, at):
        kept.append(source[at:found.start()])
        at = found.end()
        depth = 1 if found["block"] else 0
        while depth:
            edge = _RUST_BLOCK_EDGE.search(source, at)
            if edge is None:
                return "".join(kept)    # a comment that never ends
            depth += 1 if edge[0] == "/*" else -1
            at = edge.end()
        kept.append(" ")
    return "".join(kept) + source[at:]


def _rust_tests(source: str) -> list[tuple[str, ...]]:
    """Every test function of a Rust source, as `rustc --test` lists it: the inline
    modules that contain it, then its name. A function inside anything but modules (a
    function's body, an impl) is not a test."""
    # ponytail: a scanner, not the compiler -- tests and modules written by a macro or
    # removed by a `cfg` are not seen as rustc sees them. `cargo test -- --list` would
    # be, but it gives module paths without files, which is not how a target is written.
    found, open_blocks = [], []         # a module's name, or None for any other block
    for token in _RUST_TOKEN.finditer(_rust_code(source)):
        if token["module"]:
            open_blocks.append(token["module"])
        elif token["test"]:
            if None not in open_blocks:
                found.append((*open_blocks, token["test"]))
        elif token["open"]:
            open_blocks.append(None)
        elif open_blocks:
            open_blocks.pop()
    return found


def problems(text: str, repo: Path) -> list[str]:
    """What is wrong with a ledger: a function of a finished phase without a target,
    and any target that does not exist."""
    ledger = parse(text)
    found = [f"phase {n} is finished but has no 'phase {n}:' line"
             for n in ledger.finished if n not in ledger.phases]
    paths = {key.split("::")[0] for key in ledger.targets}
    found += [f"phase {n}: {glob} matches no test file"
              for n in ledger.finished for glob in ledger.phases.get(n, [])
              if not any(fnmatchcase(path, glob) for path in paths)]
    due = [glob for n in ledger.finished for glob in ledger.phases.get(n, [])]
    for key, target in ledger.targets.items():
        path = key.split("::")[0]
        if not target:
            if any(fnmatchcase(path, glob) for glob in due):
                found.append(f"{key}: no target")
        elif target.startswith("n/a"):
            # `n/a until phase <n>: <reason>` waits for a test a later phase writes, and
            # stops being an answer when that phase is finished
            waits = _PUT_OFF.match(target)
            if waits and int(waits[1]) in ledger.finished:
                found.append(f"{key}: put off until phase {waits[1]}, which is finished: "
                             "name its test")
            elif not (waits or target.startswith("n/a:")) or not target.partition(":")[2].strip():
                found.append(f"{key}: n/a without a reason")
        else:
            for one in target.split(" + "):
                if one.split(":")[0] not in ("compat", "rust"):
                    found.append(f"{key}: not a target: {one}")
                elif not _exists(one, repo):
                    found.append(f"{key}: {one} does not exist")
    return found


def main() -> None:
    old = parse(LEDGER.read_text()) if LEDGER.exists() else Ledger(header=HEADER)
    lines = [f"{key} -> {old.targets.get(key, '')}".rstrip() for key in listing(REPO)]
    LEDGER.write_text(old.header + "\n" + "\n".join(lines) + "\n")
    print(f"{LEDGER.relative_to(REPO)}: {len(lines)} test functions")


if __name__ == "__main__":
    main()
