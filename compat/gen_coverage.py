"""Writes compat/COVERAGE.md: one line per Python test function, targets kept.

    uv run python compat/gen_coverage.py
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from fnmatch import fnmatchcase
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
LEDGER = REPO / "compat" / "COVERAGE.md"
HEADER = """# Coverage ledger

One line per Python test function: where its behaviour is tested for the Rust
implementation. Generated by `compat/gen_coverage.py`, which keeps the targets
already filled in; checked by `compat/test_coverage_ledger.py`.

A target is `compat:<file>::<case>`, `rust:<crate>::<module path>::<test>`, several
of those joined by ` + `, or `n/a: <reason>`. A target that is named must exist.
When a phase is finished its number is added to `finished phases:` together with
a line `phase <n>: <glob>, <glob>, ...` naming the Python test files it covers;
from then on every function of those files needs a target.

finished phases:
"""
_TEST = re.compile(r"^\s*(?:async\s+)?def\s+(test_\w+)", re.MULTILINE)
_ENTRY = re.compile(r"^(\S+\.py::\w+) -> ?(.*)$")
_FINISHED = re.compile(r"^finished phases:(.*)$")
_PHASE = re.compile(r"^phase (\d+):(.*)$")


@dataclass
class Ledger:
    header: str = ""
    finished: list[int] = field(default_factory=list)
    phases: dict[int, list[str]] = field(default_factory=dict)
    targets: dict[str, str] = field(default_factory=dict)


def listing(repo: Path) -> list[str]:
    """`<path>::<function>` for every test function of the Python tree, sorted."""
    files = [*repo.glob("packages/*/tests/**/*.py"), *repo.glob("tools/*.py")]
    return sorted({f"{path.relative_to(repo).as_posix()}::{name}"
                   for path in files for name in _TEST.findall(path.read_text(encoding="utf-8"))})


def parse(text: str) -> Ledger:
    ledger = Ledger()
    header = []
    for line in text.splitlines():
        if entry := _ENTRY.match(line):
            ledger.targets[entry[1]] = entry[2].strip()
            continue
        if not ledger.targets:
            header.append(line)
        if finished := _FINISHED.match(line):
            ledger.finished = [int(n) for n in re.findall(r"\d+", finished[1])]
        elif phase := _PHASE.match(line):
            ledger.phases[int(phase[1])] = [g.strip() for g in phase[2].split(",") if g.strip()]
    ledger.header = "\n".join(header).rstrip("\n") + "\n"
    return ledger


def _exists(target: str, repo: Path) -> bool:
    kind, _, rest = target.partition(":")
    parts = rest.split("::")
    if kind == "compat" and len(parts) == 2:
        path = repo / "compat" / parts[0]
        return path.is_file() and re.search(rf"^def {re.escape(parts[1])}\(", path.read_text(), re.MULTILINE) is not None
    if kind == "rust" and len(parts) >= 2:
        needle = re.compile(rf"\bfn {re.escape(parts[-1])}\(")
        return any(needle.search(path.read_text()) for path in (repo / "crates" / parts[0]).rglob("*.rs"))
    return False


def problems(text: str, repo: Path) -> list[str]:
    """What is wrong with a ledger: a function of a finished phase without a target,
    and any target that does not exist."""
    ledger = parse(text)
    found = [f"phase {n} is finished but has no 'phase {n}:' line"
             for n in ledger.finished if n not in ledger.phases]
    due = [glob for n in ledger.finished for glob in ledger.phases.get(n, [])]
    for key, target in ledger.targets.items():
        path = key.split("::")[0]
        if not target:
            if any(fnmatchcase(path, glob) for glob in due):
                found.append(f"{key}: no target")
        elif target.startswith("n/a"):
            if not target.removeprefix("n/a:").strip() or not target.startswith("n/a:"):
                found.append(f"{key}: n/a without a reason")
        else:
            for one in target.split(" + "):
                if one.split(":")[0] not in ("compat", "rust"):
                    found.append(f"{key}: not a target: {one}")
                elif not _exists(one, repo):
                    found.append(f"{key}: {one} does not exist")
    return found


def main() -> None:
    old = parse(LEDGER.read_text()) if LEDGER.exists() else Ledger(header=HEADER)
    lines = [f"{key} -> {old.targets.get(key, '')}" for key in listing(REPO)]
    LEDGER.write_text(old.header + "\n" + "\n".join(lines) + "\n")
    print(f"{LEDGER.relative_to(REPO)}: {len(lines)} test functions")


if __name__ == "__main__":
    main()
